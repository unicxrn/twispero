#!/usr/bin/env python3
"""
Write projects/evoplayer/include/evo_identity.h from sce_sys/param.json.

WHY
    The app's name and title id are set in one place, sce_sys/param.json
    (localizedParameters.<defaultLanguage>.titleName and titleId). The console
    reads them from there, deploy-app.sh and package-app.sh read the title id
    from there, and this script hands both to the C++ code as two macros:

        EVO_APP_NAME   the titleName, as UTF-8
        EVO_TITLE_ID   the titleId

    include/evo_about_text.hpp turns them into evo::about::kAppName and
    kTitleId, which About, the safe-to-close page, the RmlUi fallback page and
    the start-up toast show. To rename the app, edit param.json (titleName,
    and titleId, conceptId and contentId together when the title id changes)
    and rebuild.

OUTPUT
    projects/evoplayer/include/evo_identity.h, git-ignored. Rewritten only when
    its content changes, so an unchanged name does not recompile anything.

USAGE
    python3 tools/gen_identity.py [--param FILE] [--out FILE]
    The Makefile, scripts/build-evoplayer.sh, scripts/package-app.sh,
    tools/hui_preview.sh and tools/uiview_playback_rml.sh run it before
    compiling, so nobody needs to.

No third-party dependencies - only the standard library.
"""

import argparse
import json
import os
import re
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EVO = os.path.join(REPO_ROOT, "projects", "evoplayer")
DEFAULT_PARAM = os.path.join(EVO, "sce_sys", "param.json")
DEFAULT_OUT = os.path.join(EVO, "include", "evo_identity.h")


def c_string(text: str) -> str:
    """A C string literal for text: printable ASCII as is, everything else as
    octal escapes of its UTF-8 bytes (an octal escape stops after three digits,
    so a following digit can't run into it the way it can after \\x)."""
    out = []
    for byte in text.encode("utf-8"):
        ch = chr(byte)
        if ch in '"\\':
            out.append("\\" + ch)
        elif 0x20 <= byte < 0x7F:
            out.append(ch)
        else:
            out.append("\\%03o" % byte)
    return '"' + "".join(out) + '"'


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    ap.add_argument("--param", default=DEFAULT_PARAM)
    ap.add_argument("--out", default=DEFAULT_OUT)
    args = ap.parse_args()

    with open(args.param, encoding="utf-8") as f:
        param = json.load(f)
    title_id = param.get("titleId", "")
    if not re.fullmatch(r"[A-Z]{4}\d{5}", title_id):
        sys.exit(f"gen_identity: titleId '{title_id}' in {args.param} is not four letters and five digits")
    loc = param.get("localizedParameters", {})
    name = loc.get(loc.get("defaultLanguage", ""), {}).get("titleName", "").strip()
    if not name:
        sys.exit(f"gen_identity: the default language's titleName in {args.param} is empty")

    text = (
        "/* Generated by tools/gen_identity.py from sce_sys/param.json. Don't edit\n"
        " * this file: change titleName and titleId in param.json instead. */\n"
        "#ifndef EVO_IDENTITY_H\n"
        "#define EVO_IDENTITY_H\n"
        f"#define EVO_APP_NAME {c_string(name)}\n"
        f"#define EVO_TITLE_ID {c_string(title_id)}\n"
        "#endif\n"
    )
    try:
        with open(args.out, encoding="utf-8") as f:
            unchanged = f.read() == text
    except OSError:
        unchanged = False
    if not unchanged:
        os.makedirs(os.path.dirname(args.out), exist_ok=True)
        with open(args.out, "w", encoding="utf-8") as f:
            f.write(text)
    print(f"identity: {name} ({title_id})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
