#!/usr/bin/env python3
"""
Turn Mozilla's CA roots into projects/evoplayer/addons/src/evo_ca_bundle.c.

WHY
    evo_net's EVO_NET_VERIFY_TLS requests (anything carrying a Twitch token)
    verify the server against a trust store of their own. The console has no
    CA store an app can read, so the roots are compiled in: the PEM text of
    Mozilla's root store as Ubuntu's ca-certificates package ships it in the
    dev image, one file per root under /usr/share/ca-certificates/mozilla/.
    evo_net parses it once into an X509_STORE (PEM_X509_INFO_read_bio over a
    memory BIO).

    Deliberately not /etc/ssl/certs/ca-certificates.crt: update-ca-certificates
    adds every CA dropped into /usr/local/share/ca-certificates to that file,
    so a local or corporate CA in the image would end up trusted by every
    shipped build. The mozilla directory holds Mozilla's set and nothing else.

OUTPUT
    projects/evoplayer/addons/src/evo_ca_bundle.c, git-ignored:
        const char   evo_ca_bundle_pem[];     the certificates, PEM, NUL-terminated
        const size_t evo_ca_bundle_pem_len;   its length without the NUL
    Only the BEGIN/END CERTIFICATE blocks are kept, in file-name order. The
    file is rewritten only when its content changes, so an unchanged bundle
    does not recompile. Every run prints the certificate count and the sha256
    of the generated file, so the build log records exactly what shipped.

LICENCE
    The certificates come from Mozilla's root store, MPL-2.0. The app ships the
    note in assets/licenses/ca-certificates.txt.

USAGE
    python3 tools/gen_ca_bundle.py [--in DIR_OR_PEM_FILE] [--out C_FILE]
    --in defaults to /usr/share/ca-certificates/mozilla (every *.crt in it).
    A single PEM file is for host tests only. scripts/build-evoplayer.sh and
    scripts/package-app.sh run it before compiling, and the Makefile has a
    rule for it, so nobody needs to.

No third-party dependencies - only the standard library.
"""

import argparse
import glob
import hashlib
import os
import re
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_IN = "/usr/share/ca-certificates/mozilla"
DEFAULT_OUT = os.path.join(REPO_ROOT, "projects", "evoplayer", "addons", "src", "evo_ca_bundle.c")

# Fewer than this means the input is not a real root store (the Mozilla set
# has had well over 100 for years). Better a failed build than an app that
# trusts nothing, or almost nothing.
MIN_CERTS = 50

PEM_RE = re.compile(
    r"-----BEGIN CERTIFICATE-----\r?\n[A-Za-z0-9+/=\r\n]+?-----END CERTIFICATE-----")


def c_string_lines(text):
    """The text as C string literal lines, one PEM line each."""
    out = []
    for line in text.splitlines(keepends=True):
        body = line.rstrip("\n").replace("\\", "\\\\").replace('"', '\\"')
        out.append('    "' + body + ('\\n"' if line.endswith("\n") else '"'))
    return out


def read_text(path):
    # Some bundles put each certificate's (UTF-8) name in a comment above it.
    # Only the PEM blocks are kept, and those are ASCII.
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            return f.read()
    except OSError as e:
        sys.exit(f"gen_ca_bundle: cannot read {path}: {e.strerror}")


def collect(src):
    """The certificates under src (a directory of *.crt, or one PEM file)."""
    if os.path.isdir(src):
        files = sorted(glob.glob(os.path.join(src, "*.crt")))
        if not files:
            sys.exit(f"gen_ca_bundle: no *.crt in {src}")
    elif os.path.isfile(src):
        files = [src]
    else:
        sys.exit(f"gen_ca_bundle: {src} does not exist\n"
                 "  Run inside the dev container (package ca-certificates).")
    certs = []
    for path in files:
        certs += [m.group(0).replace("\r\n", "\n") for m in PEM_RE.finditer(read_text(path))]
    return certs


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--in", dest="src", default=DEFAULT_IN)
    ap.add_argument("--out", dest="dst", default=DEFAULT_OUT)
    args = ap.parse_args()

    certs = collect(args.src)
    if len(certs) < MIN_CERTS:
        sys.exit(f"gen_ca_bundle: only {len(certs)} certificates in {args.src} "
                 f"(expected at least {MIN_CERTS})")
    pem = "\n".join(certs) + "\n"
    digest = hashlib.sha256(pem.encode("ascii")).hexdigest()

    lines = [
        "/* Generated by tools/gen_ca_bundle.py - do not edit, do not commit.",
        f" * Source: {args.src}",
        f" * {len(certs)} certificates, {len(pem)} bytes, PEM sha256 {digest}",
        " *",
        " * Mozilla's CA root store (via the ca-certificates package), MPL-2.0;",
        " * see assets/licenses/ca-certificates.txt. Read by evo_net.c for",
        " * EVO_NET_VERIFY_TLS requests. */",
        "#include <stddef.h>",
        "",
        "extern const char   evo_ca_bundle_pem[];",
        "extern const size_t evo_ca_bundle_pem_len;",
        "",
        "const char evo_ca_bundle_pem[] =",
    ]
    lines += c_string_lines(pem)
    lines[-1] += ";"
    lines += [
        "",
        "const size_t evo_ca_bundle_pem_len = sizeof evo_ca_bundle_pem - 1;",
        "",
    ]
    content = "\n".join(lines)
    file_digest = hashlib.sha256(content.encode("ascii")).hexdigest()

    shown = os.path.relpath(args.dst, REPO_ROOT)
    if shown.startswith(".."):
        shown = args.dst
    what = (f"{len(certs)} certificates from {args.src}, {len(pem)} bytes of PEM, "
            f"sha256 {file_digest}")
    try:
        with open(args.dst, "r", encoding="ascii") as f:
            if f.read() == content:
                print(f"gen_ca_bundle: {shown} up to date: {what}")
                return
    except (OSError, ValueError):
        pass
    tmp = args.dst + ".tmp"
    with open(tmp, "w", encoding="ascii", newline="\n") as f:
        f.write(content)
    os.replace(tmp, args.dst)
    print(f"gen_ca_bundle: wrote {shown}: {what}")


if __name__ == "__main__":
    main()
